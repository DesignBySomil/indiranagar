import puppeteer from 'puppeteer-core';
const b = await puppeteer.launch({executablePath:'/usr/bin/google-chrome',headless:'new',args:['--no-sandbox','--use-gl=swiftshader','--enable-unsafe-swiftshader','--window-size=1280,760']});
const p = await b.newPage();
await p.setViewport({width:1280,height:760});
p.on('pageerror',e=>console.log('PE',String(e).slice(0,250)));
p.on('console',m=>{if(m.type()==='error'&&!m.text().includes('favicon'))console.log('CERR',m.text().slice(0,150))});
await p.goto('http://localhost:4280/bldggrid.html');
await p.waitForFunction('window.__ready===true',{timeout:45000});
await new Promise(r=>setTimeout(r,600));
await p.screenshot({path:'/downloads/bldggrid.png'});
await b.close();
console.log('done');
