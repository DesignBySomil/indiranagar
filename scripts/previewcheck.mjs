import puppeteer from 'puppeteer-core';
const URL='https://htmlpreview.github.io/?https://github.com/DesignBySomil/indiranagar/blob/preview/index.html';;
const b=await puppeteer.launch({executablePath:'/usr/bin/google-chrome',headless:'new',args:['--no-sandbox','--use-gl=swiftshader','--enable-unsafe-swiftshader','--window-size=1280,800']});
const p=await b.newPage(); await p.setViewport({width:1280,height:800});
const fails=[]; p.on('requestfailed',r=>fails.push(r.url().slice(0,120)+' '+(r.failure()?.errorText||'')));
p.on('response',r=>{if(r.status()>=400)fails.push(r.url().slice(0,120)+' HTTP'+r.status());});
await p.goto(URL,{waitUntil:'domcontentloaded',timeout:90000});
await new Promise(r=>setTimeout(r,30000));
const st=await p.evaluate(()=>{try{const g=window.__game;return {game:!!g, keys:g?Object.keys(g).slice(0,15):null, auto:(g&&g.auto&&g.auto.pos)?{x:+g.auto.pos.x.toFixed(1),z:+g.auto.pos.z.toFixed(1)}:null, state:g&&g.state, title:document.title, bodyText:document.body?document.body.innerText.slice(0,200):''}}catch(e){return {err:''+e, title:document.title}}});
await p.screenshot({path:'/tmp/preview-live.png'});
console.log(JSON.stringify({st,fails:fails.slice(0,8)}));
await b.close();
