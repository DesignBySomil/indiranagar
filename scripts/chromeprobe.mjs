import puppeteer from 'puppeteer-core';
const t0=Date.now();
const b=await puppeteer.launch({executablePath:'/usr/bin/google-chrome',headless:'new',args:['--no-sandbox','--use-gl=swiftshader','--enable-unsafe-swiftshader']});
const p=await b.newPage();
await p.goto('http://localhost:4180/',{waitUntil:'domcontentloaded',timeout:60000});
console.log('goto ok', Date.now()-t0);
await p.waitForFunction(()=>window.__game&&window.__game.auto,{timeout:90000});
console.log('game ok', Date.now()-t0);
await new Promise(r=>setTimeout(r,2000));
console.log('alive after 2s', Date.now()-t0);
await b.close();
