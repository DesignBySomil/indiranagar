import puppeteer from 'puppeteer-core';
const hour = process.argv[2] || '17.5', tag = process.argv[3] || 'phone';
const b = await puppeteer.launch({ executablePath: '/usr/bin/google-chrome', headless: 'new', args: ['--no-sandbox', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const p = await b.newPage(); await p.setViewport({ width: +(process.env.W||390), height: +(process.env.H||780), isMobile: !!process.env.MOB, hasTouch: !!process.env.MOB });
p.on('pageerror', e => console.log('pageerror', e.message));
await p.goto(process.env.URL || 'http://localhost:4173/', { waitUntil: 'load' });
await p.waitForFunction('window.__game', { timeout: 90000 });
const info = await p.evaluate((h) => { const g = window.__game; g.state.hour = +h; g.state.auto = false; g.state.snap = true; g.go();
  const n = g.npcs.npcs.find(n => n.role !== 'passenger' && Math.abs(n.x) < 500 && Math.abs(n.z) < 600);
  g.auto.x = n.x + 3; g.auto.z = n.z; g.auto.v = 0; for (let k = 0; k < 15; k++) window.__step(0.05, 0); return [n.name, n.role, Math.round(n.x), Math.round(n.z)]; }, hour);
console.log(JSON.stringify(info));
await new Promise(r => setTimeout(r, 3000));
const vis = () => p.evaluate(() => { const c = document.getElementById('npc-card'); const r = c.getBoundingClientRect(); return { on: c.classList.contains('on'), text: c.innerText.replace(/\n/g,' | '), rect: [r.left|0, r.top|0, r.right|0, r.bottom|0], vw: innerWidth, vh: innerHeight }; });
console.log('before', JSON.stringify(await vis()));
await p.screenshot({ path: `/tmp/npc-${tag}-1.png` });
if (process.env.MOB) await p.tap('#npc-card'); else await p.click('#npc-card');
await new Promise(r => setTimeout(r, 1500));
console.log('after', JSON.stringify(await vis()));
await p.screenshot({ path: `/tmp/npc-${tag}-2.png` });
await b.close();
